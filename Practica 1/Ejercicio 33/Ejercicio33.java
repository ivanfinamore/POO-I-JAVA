public class Ejercicio33 {
    public static void main(String[] args) {
        int num = 6;
        for (int i = 1; i<=10;i++){
            System.out.print(i);
            System.out.print(" - ");
        }
        System.out.println();
        for (int j = 1; j<=10;j++){
            System.out.print(num*j);
            System.out.print(" - ");
        }
    }
}
